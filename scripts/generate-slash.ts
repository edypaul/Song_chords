#!/usr/bin/env npx tsx
/**
 * Generate a curated set of COMMON slash chords for guitar + ukulele.
 *
 * Piano already resolves slash chords at runtime (piano-diagrams.ts
 * splitChord + bass note), so it needs nothing here. Guitar and
 * ukulele use static tables that previously had NO slash-chord keys —
 * the fuzzy fallback just stripped the bass and showed the plain
 * chord. This script produces real slash VOICINGS (the named bass
 * note on the lowest sounding string) for the slash chords that
 * actually appear in pop / rock / worship / folk songbooks.
 *
 * Output: packages/shared/src/chord-diagrams/slash-diagrams.ts
 * Usage:  npx tsx scripts/generate-slash.ts
 */

import {
  generateGuitarSlashVoicings,
  generateUkuleleSlashVoicings,
} from '../packages/shared/src/chord-engine/voicing-generator';
import * as fs from 'fs';
import * as path from 'path';

// Curated [parentChord, bassNote] pairs — the slash chords musicians
// actually use. Grouped by purpose for readability.
const SLASH_CHORDS: Array<[string, string]> = [
  // ── Major triad inversions (3rd / 5th in bass) ──
  ['C', 'E'], ['C', 'G'],
  ['D', 'F#'], ['D', 'A'],
  ['E', 'G#'], ['E', 'B'],
  ['F', 'A'], ['F', 'C'],
  ['G', 'B'], ['G', 'D'],
  ['A', 'C#'], ['A', 'E'],
  ['Bb', 'D'], ['Bb', 'F'],
  ['B', 'D#'], ['B', 'F#'],
  ['Eb', 'G'], ['Eb', 'Bb'],
  ['Ab', 'C'], ['Ab', 'Eb'],
  // ── Minor triad inversions ──
  ['Am', 'C'], ['Am', 'E'],
  ['Em', 'G'], ['Em', 'B'],
  ['Dm', 'F'], ['Dm', 'A'],
  ['Bm', 'D'], ['Bm', 'F#'],
  ['Cm', 'Eb'], ['Cm', 'G'],
  ['Fm', 'Ab'], ['Fm', 'C'],
  ['Gm', 'Bb'], ['Gm', 'D'],
  // ── Pedal / non-chord bass (descending bass lines, very common) ──
  ['C', 'B'], ['C', 'Bb'], ['C', 'D'],
  ['G', 'F#'], ['G', 'A'], ['G', 'F'],
  ['D', 'C'], ['D', 'C#'], ['D', 'E'],
  ['F', 'G'], ['F', 'E'],
  ['A', 'G'], ['A', 'G#'],
  ['Am', 'G'], ['Am', 'F#'], ['Am', 'F'],
  ['Em', 'D'], ['Em', 'F#'],
  ['Dm', 'C'], ['Dm', 'B'],
  ['E', 'D'],
];

const outFile = path.join(
  __dirname, '..', 'packages', 'shared', 'src', 'chord-diagrams', 'slash-diagrams.ts',
);

function emit(
  label: string,
  gen: (chord: string, bass: string, count: number) => ReturnType<typeof generateGuitarSlashVoicings>,
  strings: number,
  instrument: string,
): { lines: string[]; ok: number; skipped: string[] } {
  const lines: string[] = [];
  const skipped: string[] = [];
  let ok = 0;
  for (const [chord, bass] of SLASH_CHORDS) {
    const name = `${chord}/${bass}`;
    const voicings = gen(chord, bass, 3);
    if (voicings.length === 0) { skipped.push(name); continue; }
    ok++;
    lines.push(`  '${name}': [`);
    for (const v of voicings) {
      const fretsStr = v.frets.map((f) => (f === 'x' ? "'x'" : f)).join(',');
      let extras = '';
      if (v.barre) {
        extras += `, barre:{fret:${v.barre.fret},fromString:${v.barre.fromString},toString:${v.barre.toString}}`;
      }
      lines.push(`    { name:'${name}', instrument:'${instrument}', baseFret:${v.baseFret}, strings:${strings}, frets:[${fretsStr}]${extras} },`);
    }
    lines.push('  ],');
  }
  return { lines, ok, skipped };
}

const guitar = emit('guitar', generateGuitarSlashVoicings, 6, 'guitar');
const uke = emit('ukulele', generateUkuleleSlashVoicings, 4, 'ukulele');

const out: string[] = [];
out.push("import type { ChordDiagram } from '../types/chord.types';");
out.push('');
out.push('// Curated common slash chords. Generated by');
out.push('// scripts/generate-slash.ts — do not hand-edit. Piano resolves');
out.push('// slash chords at runtime so it is intentionally not here.');
out.push('export const GUITAR_SLASH_DIAGRAMS: Record<string, ChordDiagram[]> = {');
out.push(...guitar.lines);
out.push('};');
out.push('');
out.push('export const UKULELE_SLASH_DIAGRAMS: Record<string, ChordDiagram[]> = {');
out.push(...uke.lines);
out.push('};');

fs.writeFileSync(outFile, out.join('\n') + '\n', 'utf8');

console.log(`Guitar: ${guitar.ok}/${SLASH_CHORDS.length} slash chords`);
if (guitar.skipped.length) console.log(`  skipped: ${guitar.skipped.join(', ')}`);
console.log(`Ukulele: ${uke.ok}/${SLASH_CHORDS.length} slash chords`);
if (uke.skipped.length) console.log(`  skipped: ${uke.skipped.join(', ')}`);
console.log(`Output: ${outFile}`);
