#!/usr/bin/env npx tsx
/**
 * Generate ukulele chord diagrams using the chord engine.
 *
 * Mirrors scripts/generate-chords.ts but for ukulele (GCEA, 4
 * strings). Reuses the SAME formula-based voicing generator — the
 * engine is parameterized on tuning/string-count, so ukulele gets the
 * same tier1/tier2 tone logic, playability filter, barre rules, and
 * scoring that guitar uses. Output replaces the previously
 * hand-written (basic-chords-only) ukulele-diagrams.ts so every chord
 * type now exists in every key.
 *
 * Usage: npx tsx scripts/generate-ukulele.ts
 */

import { CHORD_FORMULAS } from '../packages/shared/src/chord-engine/formulas';
import { generateUkuleleVoicings } from '../packages/shared/src/chord-engine/voicing-generator';
import * as fs from 'fs';
import * as path from 'path';

const ROOTS = ['C', 'C#', 'D', 'Eb', 'E', 'F', 'F#', 'G', 'Ab', 'A', 'Bb', 'B'];
// Upper bound on variations per chord; selector may return fewer
// (1–4) — no high-neck filler padding.
const VOICINGS_PER_CHORD = 4;

const outFile = path.join(__dirname, '..', 'packages', 'shared', 'src', 'chord-diagrams', 'ukulele-diagrams.ts');

const lines: string[] = [];
lines.push("import type { ChordDiagram } from '../types/chord.types';");
lines.push('');
lines.push('// Ukulele tuning: G C E A (strings 4-1). Generated by');
lines.push('// scripts/generate-ukulele.ts — do not hand-edit.');
lines.push('export const UKULELE_DIAGRAMS: Record<string, ChordDiagram[]> = {');

let totalChords = 0;
let totalVoicings = 0;
const emptyChords: string[] = [];

for (const root of ROOTS) {
  for (const formula of CHORD_FORMULAS) {
    const chordName = root + formula.suffix;
    const voicings = generateUkuleleVoicings(chordName, VOICINGS_PER_CHORD);

    totalChords++;
    totalVoicings += voicings.length;

    if (voicings.length === 0) {
      emptyChords.push(chordName);
      continue;
    }

    lines.push(`  '${chordName}': [`);
    for (const v of voicings) {
      const fretsStr = v.frets.map((f) => (f === 'x' ? "'x'" : f)).join(',');
      let extras = '';
      if (v.barre) {
        extras += `, barre:{fret:${v.barre.fret},fromString:${v.barre.fromString},toString:${v.barre.toString}}`;
      }
      lines.push(`    { name:'${chordName}', instrument:'ukulele', baseFret:${v.baseFret}, strings:4, frets:[${fretsStr}]${extras} },`);
    }
    lines.push('  ],');
  }
}

lines.push('};');

fs.writeFileSync(outFile, lines.join('\n') + '\n', 'utf8');

console.log(`Generated ${totalVoicings} voicings for ${totalChords} chords (${VOICINGS_PER_CHORD} per chord)`);
console.log(`Output: ${outFile}`);
if (emptyChords.length > 0) {
  console.error(`WARNING: No voicings generated for: ${emptyChords.join(', ')}`);
}
